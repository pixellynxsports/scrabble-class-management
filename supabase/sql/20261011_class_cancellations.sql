-- Class cancellation support.
-- Stores cancellation per Sunday and per class session without creating attendance rows.

create table if not exists public.class_cancellations (
  id bigint generated by default as identity primary key,
  cancellation_date date not null,
  class_time text not null check (class_time in ('10:30 AM','2:00 PM')),
  cancelled_by uuid,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (cancellation_date, class_time)
);

alter table public.class_cancellations enable row level security;

drop policy if exists "Teachers can read class cancellations" on public.class_cancellations;
create policy "Teachers can read class cancellations"
on public.class_cancellations
for select
to authenticated
using (true);

drop policy if exists "Teachers can create class cancellations" on public.class_cancellations;
create policy "Teachers can create class cancellations"
on public.class_cancellations
for insert
to authenticated
with check (true);

drop policy if exists "Teachers can update class cancellations" on public.class_cancellations;
create policy "Teachers can update class cancellations"
on public.class_cancellations
for update
to authenticated
using (true)
with check (true);

drop policy if exists "Teachers can delete class cancellations" on public.class_cancellations;
create policy "Teachers can delete class cancellations"
on public.class_cancellations
for delete
to authenticated
using (true);

create index if not exists idx_class_cancellations_date
on public.class_cancellations(cancellation_date);

-- Explicit Data API grants are required for tables created by SQL migrations
-- on Supabase projects with automatic exposure disabled.
grant select, insert, update, delete on table public.class_cancellations to authenticated, service_role;
grant usage, select on sequence public.class_cancellations_id_seq to authenticated, service_role;
